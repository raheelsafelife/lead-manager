function normalizeMatchText(value = "") {
  return String(value || "").toLowerCase().replace(/[^a-z0-9]/g, "");
}

function levenshteinDistance(a = "", b = "") {
  const left = normalizeMatchText(a);
  const right = normalizeMatchText(b);
  if (!left) return right.length;
  if (!right) return left.length;
  const previous = Array.from({ length: right.length + 1 }, (_value, index) => index);
  const current = Array(right.length + 1).fill(0);
  for (let i = 1; i <= left.length; i += 1) {
    current[0] = i;
    for (let j = 1; j <= right.length; j += 1) {
      current[j] = left[i - 1] === right[j - 1]
        ? previous[j - 1]
        : Math.min(previous[j - 1], previous[j], current[j - 1]) + 1;
    }
    for (let j = 0; j <= right.length; j += 1) previous[j] = current[j];
  }
  return previous[right.length];
}

function fuzzyLeadScore(lead, tokens) {
  const nameTokens = `${lead.first_name || ""} ${lead.last_name || ""}`.toLowerCase().split(/\s+/).filter(Boolean);
  if (!tokens.length || !nameTokens.length) return 999;
  return tokens.reduce((score, token) => {
    const best = Math.min(...nameTokens.map((nameToken) => {
      const normalizedToken = normalizeMatchText(token);
      const normalizedName = normalizeMatchText(nameToken);
      if (normalizedName.includes(normalizedToken) || normalizedToken.includes(normalizedName)) return 0;
      return levenshteinDistance(normalizedToken, normalizedName);
    }));
    return score + best;
  }, 0);
}

