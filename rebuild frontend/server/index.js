function timeZoneParts(date = new Date(), timeZone = digestTimeZone) {
  return Object.fromEntries(new Intl.DateTimeFormat("en-US", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false
  }).formatToParts(date).filter((part) => part.type !== "literal").map((part) => [part.type, part.value]));
}

function digestDateString(date = new Date()) {
  const parts = timeZoneParts(date);
  return `${parts.year}-${parts.month}-${parts.day}`;
}

function digestDateOffset(days) {
  return digestDateString(new Date(Date.now() + days * 24 * 60 * 60 * 1000));
}

function digestLocalHour(date = new Date()) {
  return Number(timeZoneParts(date).hour || 0);
}

function digestLocalMinute(date = new Date()) {
  return Number(timeZoneParts(date).minute || 0);
}

function timeZoneOffsetMs(date, timeZone = digestTimeZone) {
  const parts = timeZoneParts(date, timeZone);
  const asUtc = Date.UTC(parts.year, Number(parts.month) - 1, parts.day, parts.hour, parts.minute, parts.second);
  return asUtc - date.getTime();
}

function zonedTimeToUtc(year, month, day, hour, minute = 0, second = 0, timeZone = digestTimeZone) {
  const target = Date.UTC(year, month - 1, day, hour, minute, second);
  let utc = new Date(target);
  utc = new Date(target - timeZoneOffsetMs(utc, timeZone));
  return new Date(target - timeZoneOffsetMs(utc, timeZone));
}

function digestWindowUtc(digestDate) {
  const [year, month, day] = digestDate.split("-").map(Number);
  const start = zonedTimeToUtc(year, month, day, 0, 0, 0);
  const end = zonedTimeToUtc(year, month, day + 1, 0, 0, 0);
  return {
    start: start.toISOString().replace("T", " ").replace("Z", ""),
    end: end.toISOString().replace("T", " ").replace("Z", "")
  };
}

