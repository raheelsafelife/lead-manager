function scoreKnowledgeChunk(chunk, tokens) {
  const content = normalizeMatchText(chunk.content || "");
  const title = normalizeMatchText(chunk.title || "");
  return tokens.reduce((score, token) => {
    if (title.includes(token)) return score + 3;
    if (content.includes(token)) return score + 1;
    return score;
  }, 0);
}

async function searchKnowledgeBase(message = "") {
  const tokens = searchTokensForKnowledge(message);
  if (!tokens.length) return [];
  const where = tokens.map((_, index) => `lower(knowledge_chunks.content) like @token${index} or lower(knowledge_documents.title) like @token${index}`).join(" or ");
  const params = Object.fromEntries(tokens.map((token, index) => [`token${index}`, `%${token}%`]));
  const rows = await db.all(`
    select knowledge_chunks.id, knowledge_chunks.document_id, knowledge_chunks.chunk_index, knowledge_chunks.content,
      knowledge_documents.title, knowledge_documents.source_type
    from knowledge_chunks
    join knowledge_documents on knowledge_documents.id = knowledge_chunks.document_id
    where ${where}
    limit 25
  `, params);
  return rows
    .map((row) => ({ ...row, score: scoreKnowledgeChunk(row, tokens) }))
    .filter((row) => row.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 5);
}

