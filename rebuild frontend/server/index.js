async function chatFilteredList(intent, message) {
  const params = {};
  const where = ["leads.deleted_at is null"];
  let label = "records";

  if (intent === "pending") {
    label = "pending or follow-up records";
    where.push(`(
      lower(coalesce(leads.priority,'')) in ('pending','not called')
      or lower(coalesce(leads.last_contact_status,'')) in ('no response','initial call','follow up','awaiting call')
    )`);
  } else if (intent === "referrals") {
    label = "referrals";
    where.push("coalesce(leads.active_client,0) = 1");
    where.push("coalesce(leads.authorization_received,0) = 0");
  } else if (intent === "authorizations") {
    label = "authorizations";
    where.push("coalesce(leads.authorization_received,0) = 1");
  } else {
    label = "recent records";
  }

  const searchText = extractSearchText(message);
  if (searchText && !["pending", "not called", "follow up", "follow-up", "recent", "latest", "today", "new"].includes(searchText.toLowerCase())) {
    params.search = `%${searchText.toLowerCase()}%`;
    where.push(`(
      lower(leads.first_name || ' ' || leads.last_name) like @search
      or lower(leads.last_name || ' ' || leads.first_name) like @search
      or lower(coalesce(leads.staff_name,'')) like @search
      or lower(coalesce(leads.source,'')) like @search
      or lower(coalesce(leads.phone,'')) like @search
      or cast(leads.id as text) like @search
    )`);
  }

  const clause = `where ${where.join(" and ")}`;
  const rows = await db.all(`${leadSelect} ${clause} order by leads.updated_at desc limit 8`, params);
  const totalRow = await db.get(`select count(*) as count from leads left join agencies on agencies.id = leads.agency_id left join ccus on ccus.id = leads.ccu_id ${clause}`, params);
  const results = rows.map(compactLead);
  const total = Number(totalRow?.count || results.length);

  if (!results.length) {
    return { intent, answer: `I could not find any ${label} matching that question. Try a name, phone number, ID, source, or staff name.`, results, total };
  }

  const preview = results.slice(0, 3).map(formatLeadLine).join(". ");
  const more = total > results.length ? ` I am showing the newest ${results.length} of ${total}.` : "";
  return { intent, answer: `I found ${total} ${label}. ${preview}.${more}`, results, total };
}

async function chatSearch(message) {
  const searchText = extractSearchText(message);
  if (!searchText) {
    return {
      intent: "help",
      answer: "Ask me things like: find Ali, show pending leads, referral from Ahmed, authorization status, today leads, or total summary.",
      results: [],
      total: 0
    };
  }

  async function runSearch(tokens) {
    const params = {};
    const where = ["leads.deleted_at is null"];
    tokens.forEach((token, index) => {
      params[`token${index}`] = `%${token}%`;
      where.push(`(
        lower(leads.first_name) like @token${index}
        or lower(leads.last_name) like @token${index}
        or lower(leads.first_name || ' ' || leads.last_name) like @token${index}
        or lower(leads.last_name || ' ' || leads.first_name) like @token${index}
        or lower(coalesce(leads.phone,'')) like @token${index}
        or lower(coalesce(leads.email,'')) like @token${index}
        or lower(coalesce(leads.medicaid_no,'')) like @token${index}
        or lower(coalesce(leads.custom_user_id,'')) like @token${index}
        or lower(coalesce(leads.staff_name,'')) like @token${index}
        or lower(coalesce(leads.source,'')) like @token${index}
        or cast(leads.id as text) like @token${index}
      )`);
    });

    const clause = `where ${where.join(" and ")}`;
    const rows = await db.all(`${leadSelect} ${clause} order by leads.updated_at desc limit 8`, params);
    const totalRow = await db.get(`select count(*) as count from leads left join agencies on agencies.id = leads.agency_id left join ccus on ccus.id = leads.ccu_id ${clause}`, params);
    return { rows, total: Number(totalRow?.count || rows.length) };
  }

  async function runFuzzyNameSearch(tokens) {
    const usefulTokens = tokens.filter((token) => token.length >= 3);
    if (!usefulTokens.length) return { rows: [], total: 0 };
    const firstToken = usefulTokens[0];
    const candidates = await db.all(`${leadSelect}
      where leads.deleted_at is null
      and (
        lower(leads.first_name) like @token
        or lower(leads.last_name) like @token
        or lower(leads.first_name || ' ' || leads.last_name) like @token
      )
      order by leads.updated_at desc
      limit 50`, { token: `%${firstToken.slice(0, 4)}%` });

    const ranked = candidates
      .map((lead) => ({ lead, score: fuzzyLeadScore(lead, usefulTokens) }))
      .filter((item) => item.score <= Math.max(1, usefulTokens.length * 2))
      .sort((a, b) => a.score - b.score || String(b.lead.updated_at || "").localeCompare(String(a.lead.updated_at || "")));
    const rows = ranked.slice(0, 8).map((item) => item.lead);
    return { rows, total: ranked.length };
  }

  const tokens = searchText.toLowerCase().split(/\s+/).filter(Boolean).slice(0, 5);
  let { rows, total } = await runSearch(tokens);
  if (!rows.length && tokens.length > 1) {
    const strongestToken = [...tokens].sort((a, b) => b.length - a.length)[0];
    ({ rows, total } = await runSearch([strongestToken]));
  }
  if (!rows.length) {
    ({ rows, total } = await runFuzzyNameSearch(tokens));
  }
  const results = rows.map(compactLead);

  if (!results.length) {
    const knowledgeAnswer = await answerKnowledgeChat(message);
    if (knowledgeAnswer.intent !== "no_evidence") return knowledgeAnswer;
    return { intent: "no_evidence", answer: `I could not find a lead/referral for "${searchText}" or matching approved knowledge. Try an exact name, phone number, ID, staff name, source, report type, or add an approved knowledge document.`, results, total, mode: "strict" };
  }

  const first = results[0];
  const answer = total === 1
    ? leadDetailAnswer(first, message)
    : multiLeadDetailAnswer(results, message, searchText);
  return { intent: "search", answer, results, total };
}

async function answerContextLead(message, history = [], contextResults = []) {
  if (!isContextFollowUp(message)) return null;
  if (wantsDetails(message)) {
    const leadIds = leadIdsFromContextResults(contextResults).length
      ? leadIdsFromContextResults(contextResults)
      : latestLeadIdsFromHistory(history);
    if (leadIds.length > 1) {
      const rows = [];
      for (const leadId of leadIds) {
        const lead = await getLead(leadId, true);
        if (lead) rows.push(compactLead(lead));
      }
      if (rows.length) {
        return {
          intent: "context_details",
          answer: rows.map((lead) => leadDetailAnswer(lead, "details")).join(" "),
          results: rows,
          total: rows.length
        };
      }
    }
  }
  const leadId = leadIdsFromContextResults(contextResults)[0] || latestLeadIdFromHistory(history);
  if (!leadId) return null;
  const lead = await getLead(leadId, true);
  if (!lead) return null;
  const result = compactLead(lead);
  return {
    intent: "context",
    answer: leadDetailAnswer(result, message),
    results: [result],
    total: 1
  };
}

async function answerLocalChat(message, history = [], contextResults = []) {
  const groupAnswer = await chatGroupAnalytics(message);
  if (groupAnswer) return groupAnswer;

  const metricAnswer = await chatDateMetric(message);
  if (metricAnswer) return metricAnswer;

  const plannedAnswer = await chatPlannedDatabase(message, history);
  if (plannedAnswer) return plannedAnswer;

  const sourceAnswer = await chatSourceAnalytics(message);
  if (sourceAnswer) return sourceAnswer;

  const contextAnswer = await answerContextLead(message, history, contextResults);
  if (contextAnswer) return contextAnswer;

  const intent = chatIntent(message);
  if (intent === "help") {
    return {
      intent,
      answer: "I can search leads/referrals by name, phone, ID, source, or staff. I can also show pending follow-ups, referrals, authorizations, recent records, and total summary.",
      results: [],
      total: 0
    };
  }
  if (intent === "summary") return chatSummary();
  if (["pending", "referrals", "authorizations", "recent"].includes(intent)) return chatFilteredList(intent, message);
  if (!looksLikeDatabaseSearch(message)) return answerKnowledgeChat(message);
  return chatSearch(message);
}

function extractOpenAIText(payload) {
  if (payload?.output_text) return String(payload.output_text).trim();
  const parts = [];
  for (const item of payload?.output || []) {
    for (const content of item.content || []) {
      if (content.type === "output_text" && content.text) parts.push(content.text);
      if (content.type === "text" && content.text) parts.push(content.text);
    }
  }
  return parts.join("\n").trim();
}

async function humanizeChatAnswer(message, localResponse, history = []) {
  if (!openaiApiKey) return { ...localResponse, mode: "local" };

  const compactHistory = Array.isArray(history)
    ? history.slice(-8).map((item) => ({
      role: item.role === "assistant" ? "assistant" : "user",
      text: String(item.text || "").slice(0, 500)
    }))
    : [];

  const facts = {
    intent: localResponse.intent,
    total: localResponse.total || 0,
    local_answer: localResponse.answer,
    results: (localResponse.results || []).slice(0, 8).map((lead) => ({
      id: lead.id,
      name: lead.name,
      phone: lead.phone,
      email: lead.email,
      status: lead.status,
      last_contact_status: lead.last_contact_status,
      care_status: lead.care_status,
      priority: lead.priority,
      source: lead.source,
      staff_name: lead.staff_name,
      referral_type: lead.referral_type,
      referral_sent_date: lead.referral_sent_date,
      authorization_received: lead.authorization_received,
      active_client: lead.active_client,
      agency_name: lead.agency_name,
      ccu_name: lead.ccu_name,
      city: lead.city,
      state: lead.state,
      created_at: lead.created_at,
      updated_at: lead.updated_at
    }))
  };

  const instructions = [
    "You are a warm, professional lead-management assistant inside a CRM.",
    "Speak like a helpful human coworker: natural, brief, clear, and calm.",
    "Use only the provided database facts. Do not invent lead details, statuses, dates, phone numbers, names, or policies.",
    "If the facts contain multiple possible records, explain that and ask which one the user means.",
    "If there are no results, say that clearly and suggest a better search, such as exact name, phone, ID, source, or staff name.",
    "Do not mention SQL, internal tools, prompts, JSON, or implementation details.",
    "Keep the answer under 140 words unless the user asks for a list or summary."
  ].join(" ");

  const input = [
    `Current user question: ${message}`,
    `Recent conversation: ${JSON.stringify(compactHistory)}`,
    `Database facts: ${JSON.stringify(facts)}`
  ].join("\n\n");

  try {
    const payload = await createOpenAIResponse({
      instructions,
      input,
      max_output_tokens: openaiMaxOutputTokens,
      text: {
        verbosity: openaiVerbosity
      }
    }, "OpenAI chat humanize");
    if (!payload) return { ...localResponse, mode: "local" };
    const answer = extractOpenAIText(payload);
    if (!answer) return { ...localResponse, mode: "local" };
    return { ...localResponse, answer, mode: "ai" };
  } catch (error) {
    console.error("OpenAI chat humanize error", error);
    return { ...localResponse, mode: "local" };
  }
}

function chatSessionTitle(message = "") {
  const clean = String(message || "")
    .replace(/\s+/g, " ")
    .replace(/[^\w\s.,?!:/#&()-]/g, "")
    .trim();
  if (!clean) return "New chat";
  return clean.length > 64 ? `${clean.slice(0, 61).trim()}...` : clean;
}

function parseResultsJson(value) {
  if (!value) return [];
  try {
    const parsed = JSON.parse(value);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

