function localDateString(date = new Date()) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function monthNameToIndex(name = "") {
  return [
    "january", "february", "march", "april", "may", "june",
    "july", "august", "september", "october", "november", "december"
  ].findIndex((month) => month.startsWith(name.toLowerCase()));
}

function parseSpecificDate(message = "") {
  const text = message.toLowerCase();
  const iso = text.match(/\b(20\d{2})[-/](\d{1,2})[-/](\d{1,2})\b/);
  if (iso) {
    return `${iso[1]}-${String(iso[2]).padStart(2, "0")}-${String(iso[3]).padStart(2, "0")}`;
  }
  const slash = text.match(/\b(\d{1,2})\/(\d{1,2})\/(20\d{2})\b/);
  if (slash) {
    return `${slash[3]}-${String(slash[1]).padStart(2, "0")}-${String(slash[2]).padStart(2, "0")}`;
  }
  const named = text.match(/\b(jan(?:uary)?|feb(?:ruary)?|mar(?:ch)?|apr(?:il)?|may|jun(?:e)?|jul(?:y)?|aug(?:ust)?|sep(?:t(?:ember)?)?|oct(?:ober)?|nov(?:ember)?|dec(?:ember)?)\s+(\d{1,2})(?:st|nd|rd|th)?(?:,\s*(20\d{2}))?\b/);
  if (named) {
    const monthIndex = monthNameToIndex(named[1]);
    const year = named[3] || new Date().getFullYear();
    return `${year}-${String(monthIndex + 1).padStart(2, "0")}-${String(named[2]).padStart(2, "0")}`;
  }
  return null;
}

function parseChatDateRange(message = "") {
  const text = normalizeChatText(message);
  const today = new Date();
  const specific = parseSpecificDate(message);
  if (specific) return { startDate: specific, endDate: specific, label: specific };

  const lastDays = text.match(/\b(?:last|past|previous)\s+(\d{1,3})\s+days?\b/);
  if (lastDays) {
    const days = Math.min(Math.max(Number(lastDays[1]), 1), 365);
    return {
      startDate: localDateString(addDays(today, -days)),
      endDate: localDateString(today),
      label: `the last ${days} days`
    };
  }

  const lastMonths = text.match(/\b(?:last|past|previous)\s+(\d{1,2})\s+months?\b/);
  if (lastMonths) {
    const months = Math.min(Math.max(Number(lastMonths[1]), 1), 24);
    const start = new Date(today.getFullYear(), today.getMonth() - months, today.getDate());
    return {
      startDate: localDateString(start),
      endDate: localDateString(today),
      label: `the last ${months} months`
    };
  }

  if (/\b(today|todays)\b/.test(text)) {
    const day = localDateString(today);
    return { startDate: day, endDate: day, label: "today" };
  }
  if (/\b(yesterday|last day|previous day)\b/.test(text)) {
    const day = localDateString(addDays(today, -1));
    return { startDate: day, endDate: day, label: "yesterday" };
  }
  if (/\b(last week|past week|previous week)\b/.test(text)) {
    return {
      startDate: localDateString(addDays(today, -7)),
      endDate: localDateString(today),
      label: "the last 7 days"
    };
  }
  if (/\b(last month|previous month)\b/.test(text)) {
    const start = new Date(today.getFullYear(), today.getMonth() - 1, 1);
    const end = new Date(today.getFullYear(), today.getMonth(), 0);
    return { startDate: localDateString(start), endDate: localDateString(end), label: "last month" };
  }
  if (/\b(this month|current month)\b/.test(text)) {
    const start = new Date(today.getFullYear(), today.getMonth(), 1);
    return { startDate: localDateString(start), endDate: localDateString(today), label: "this month" };
  }
  return null;
}

function currentMonthRange() {
  const today = new Date();
  const start = new Date(today.getFullYear(), today.getMonth(), 1);
  return { startDate: localDateString(start), endDate: localDateString(today), label: "this month" };
}

function normalizeChatText(message = "") {
  return String(message || "")
    .toLowerCase()
    .replace(/[’']/g, "")
    .replace(/\btodays\b/g, "today")
    .replace(/\bmanu\b/g, "many")
    .replace(/\breciev(?:e|ed|ing)?\b/g, "receive")
    .replace(/\breceivd\b/g, "received")
    .replace(/\brefer(?:a|e)l(s)?\b/g, "referral$1")
    .replace(/\breferr?al(s)?\b/g, "referral$1")
    .replace(/\bauthori[sz]e?ation(s)?\b/g, "authorization$1")
    .replace(/\s+/g, " ")
    .trim();
}

function hasApproxWord(message = "", target = "", maxDistance = 2) {
  const normalizedTarget = normalizeMatchText(target);
  return normalizeChatText(message).split(/\s+/).some((word) => {
    const normalizedWord = normalizeMatchText(word);
    if (!normalizedWord) return false;
    if (normalizedWord.includes(normalizedTarget) || normalizedTarget.includes(normalizedWord)) return true;
    return levenshteinDistance(normalizedWord, normalizedTarget) <= maxDistance;
  });
}

