app.patch("/api/leads/:id", auth, async (req, res) => {
  const oldLead = await getLead(req.params.id, true);
  if (!oldLead) return res.status(404).json({ error: "Lead not found" });
  const allowed = Object.keys(req.body).filter((k) => leadWriteFields.has(k));
  if (!allowed.length) return res.json({ lead: oldLead });
  const data = Object.fromEntries(allowed.map((key) => [key, req.body[key]]));
  const proposedLead = { ...oldLead, ...data };
  const metricFieldsChanged = allowed.some((key) => ["active_client", "authorization_received", "care_status", "referral_sent_date"].includes(key));
  if (metricFieldsChanged) {
    const metricErrors = validateLeadMetricState(proposedLead);
    if (metricErrors.length) return res.status(400).json({ error: metricErrors.join(" ") });
  }
  data.id = req.params.id;
  data.updated_at = now();
  data.updated_by = req.user.username;
  if (allowed.includes("authorization_received_at")) {
    data.authorization_received_at = data.authorization_received_at ? String(data.authorization_received_at).slice(0, 10) : null;
  }
  if (allowed.includes("authorization_received")) {
    const hadAuthorization = Number(oldLead.authorization_received || 0) === 1;
    const hasAuthorization = Number(data.authorization_received || 0) === 1;
    if (!hadAuthorization && hasAuthorization) {
      data.authorization_received_at = data.authorization_received_at || data.updated_at;
      if (!allowed.includes("authorization_received_at")) allowed.push("authorization_received_at");
    } else if (hasAuthorization && !oldLead.authorization_received_at) {
      data.authorization_received_at = data.authorization_received_at || data.updated_at;
      if (!allowed.includes("authorization_received_at")) allowed.push("authorization_received_at");
    } else if (hadAuthorization && !hasAuthorization) {
      data.authorization_received_at = null;
      if (!allowed.includes("authorization_received_at")) allowed.push("authorization_received_at");
    }
  }
  const sets = [...allowed, "updated_at", "updated_by"].map((k) => `${k} = @${k}`).join(",");
  await db.run(`update leads set ${sets} where id = @id`, data);
  const lead = await getLead(req.params.id, true);
  const actionType = req.body.care_status === "Care Start"
    ? "CARE_START_MARKED"
    : Number(req.body.authorization_received) === 1
      ? "AUTHORIZATION_MARKED"
      : Number(req.body.active_client) === 1 && Number(req.body.authorization_received) === 0
        ? "REFERRAL_MARKED"
        : "UPDATE_LEAD";
  const changedFields = changedNotificationFields(oldLead, lead);
  const description = changedFields.length === 1
    ? `${changedFields[0].label} changed from "${changedFields[0].before}" to "${changedFields[0].after}" for '${lead.first_name} ${lead.last_name}'`
    : changedFields.length > 1
      ? `Updated ${changedFields.length} fields for '${lead.first_name} ${lead.last_name}': ${changedFields.slice(0, 3).map((field) => field.label).join(", ")}${changedFields.length > 3 ? ", ..." : ""}`
      : actionType === "CARE_START_MARKED"
        ? `Marked Care Start for '${lead.first_name} ${lead.last_name}'`
        : actionType === "AUTHORIZATION_MARKED"
          ? `Marked authorization for '${lead.first_name} ${lead.last_name}'`
          : actionType === "REFERRAL_MARKED"
            ? `Marked referral for '${lead.first_name} ${lead.last_name}'`
            : `Updated lead '${lead.first_name} ${lead.last_name}'`;
  await logActivity(req.user, actionType, "Lead", lead.id, `${lead.first_name} ${lead.last_name}`, description, oldLead, lead, "lead,update");
  res.json({ lead });
});

